"""Zerodha Kite Connect market-data provider.

Calls the documented REST and WebSocket APIs directly - no ``kiteconnect``
SDK. The SDK's ``KiteTicker`` runs on Twisted, whose reactor cannot be
restarted within a process, and this service reconnects feeds as a matter of
course. ``requests`` + ``websockets`` (already installed) cover everything, as
they do for Dhan and INDmoney.

References (Kite Connect v3, https://kite.trade/docs/connect/v3/):
  - Login / token   : market/providers/kite_session.py, scripts/kite_login.py
  - Instrument ids  : read from data/kite_instruments.json, generated by
                      scripts/fetch_kite_instruments.py - never downloaded here
  - Quotes          : GET https://api.kite.trade/quote{,/ohlc,/ltp}?i=NSE:INFY
  - Daily candles   : GET https://api.kite.trade/instruments/historical/{token}/day
  - Live feed       : wss://ws.kite.trade?api_key=...&access_token=...

Kite identifies an instrument two ways, and each API uses one of them:
REST quotes are keyed by ``NSE:<tradingsymbol>`` (``NSE:NIFTY BANK``), while
the websocket and historical candles use the numeric ``instrument_token``. The
instrument file carries both; ``InstrumentRef.provider_id`` is the token.

Market data needs the paid Kite Connect plan; the free "Personal" plan has
orders and portfolio only. ``connect()`` probes a quote so a key without the
data plan fails there, loudly, instead of producing an empty board.

Read-only by construction: this module calls no order, GTT, alert or
portfolio-mutating endpoint, and the tests assert that.
"""

