"""How big each tile is in its index, how much it moved the index, and tile order.

Pure functions only - no API calls, no Streamlit. Weights are the stored
free-float market caps (``market/weights.py``, generated by
``scripts/dhan.py --master``); nothing here fetches anything.

Two boards, two meanings of "size" and "impact":

Nifty 50 sector board (``attach_sector_impact``)
    *Size* is the sector's share of the index: the free-float market cap of its
    members over that of every member we hold a weight for. *Impact* is the
    sector's contribution to the index move, in percent of the index::

        impact = sum(member free-float cap x member % change) / index free-float cap
               = share x market-cap-weighted sector % change

    Impact is computed from market-cap weights - that is what actually moves
    the index - the same weights behind the market-cap weighted % on the tile.
    A sector with no weighted member has no impact (``None``), even though its
    tile still shows a plain-average %. Where the index's previous close is known it is also given in index
    points: ``impact % x previous close / 100``. The board's own feed carries
    the index (``MarketSnapshot.index``) for exactly this; ``index_points_note``
    says why when points cannot be shown.

NSE sectoral index board (``attach_index_weights``)
    Indices overlap (Nifty Bank sits inside Nifty Financial Services, and every
    one sits inside Nifty 500), so "share of Nifty" means nothing there.
    *Size* is the index's free-float market cap, summed over its constituents;
    *impact* is that cap times the index's own % change - the rupee value its
    constituents gained or lost today.

Both are approximations of NSE's own index weights: our free float is market
cap x (1 - promoter holding), and NSE also caps single-stock weights.

Ordering (``order_sectors``)
    ``impact``       largest *absolute* impact first, so a big fall ranks with a
                     big rise; colour still shows the direction.
    ``size``         largest weight first. Weights are fixed for the session, so
                     tiles stay put while you click.
    ``performance``  largest % change first, as shown on the tile.

A tile with no usable weight never gets a made-up one: it ranks after every
weighted tile under ``impact`` and ``size`` (by name, so it does not jump), and
the page says how many such tiles there are.
"""

import dataclasses
from typing import Dict, Iterable, List, Optional, Sequence

from market.models import SectorMarketData, StockMarketData
from market.sector_aggregation import rank_sectors, weighted_change_pct

#: Tile ordering strategies (see docs/SECTOR_HEATMAP.md). The first is the default.
ORDER_BY_IMPACT = "impact"
ORDER_BY_SIZE = "size"
ORDER_BY_PERFORMANCE = "performance"
ORDERS = (ORDER_BY_IMPACT, ORDER_BY_SIZE, ORDER_BY_PERFORMANCE)

#: Sidebar labels, in display order.
ORDER_LABELS: Dict[str, str] = {
    ORDER_BY_IMPACT: "Biggest impact first",
    ORDER_BY_SIZE: "Largest sector first",
    ORDER_BY_PERFORMANCE: "Biggest move first",
}

CRORE = 1e7
LAKH_CRORE = 1e12


def _usable(weight: Optional[float]) -> bool:
    return weight is not None and weight > 0


def attach_sector_impact(
    sectors: Iterable[SectorMarketData],
    stocks: Sequence[StockMarketData],
    weights: Optional[Dict[str, float]],
    index_previous_close: Optional[float] = None,
) -> List[SectorMarketData]:
    """The Nifty 50 board's sectors with their index share and impact filled in.

    ``stocks`` is the whole universe (every member of the index), so the share
    is taken over the index rather than over one sector. A member with no
    weight is left out of both sides of the share, and the sector records how
    many of its members carried one. A sector with none gets no share and no
    impact rather than a zero.
    """
    weights = weights or {}
    index_cap = sum(weights[s.symbol] for s in stocks if _usable(weights.get(s.symbol)))

    by_sector: Dict[str, List[StockMarketData]] = {}
    for stock in stocks:
        by_sector.setdefault(stock.sector, []).append(stock)

    result = []
    for sector in sectors:
        members = by_sector.get(sector.sector, [])
        weighted = [m for m in members if _usable(weights.get(m.symbol))]
        cap = sum(weights[m.symbol] for m in weighted)
        if not weighted or index_cap <= 0:
            result.append(dataclasses.replace(sector, weighted_members=0, member_total=len(members)))
            continue

        priced = [m for m in weighted if m.change_pct is not None]
        cap_change = weighted_change_pct(
            [m.change_pct for m in priced], [weights[m.symbol] for m in priced]
        )
        impact_value = (
            sum(weights[m.symbol] * m.change_pct for m in priced) / 100.0 if priced else None
        )
        impact_pct = None if impact_value is None else impact_value / index_cap * 100.0
        points = (
            impact_pct * index_previous_close / 100.0
            if impact_pct is not None and index_previous_close and index_previous_close > 0
            else None
        )
        result.append(
            dataclasses.replace(
                sector,
                free_float_cap=cap,
                index_share_pct=cap / index_cap * 100.0,
                cap_weighted_change_pct=cap_change,
                impact_value=impact_value,
                index_impact_pct=impact_pct,
                index_impact_points=points,
                weighted_members=len(weighted),
                member_total=len(members),
            )
        )
    return result


def attach_index_weights(
    sectors: Iterable[SectorMarketData],
    members: Dict[str, Sequence[str]],
    weights: Optional[Dict[str, float]],
) -> List[SectorMarketData]:
    """The index board's tiles with their free-float cap and rupee impact.

    ``members`` maps a tile label to its index's constituent symbols (NSE's
    published lists, stored by ``--master``). The cap is the sum over the
    constituents we hold a weight for; ``weighted_members`` says how many that
    was, so a partial sum is never passed off as the whole index.
    """
    weights = weights or {}
    result = []
    for sector in sectors:
        symbols = list(members.get(sector.sector) or ())
        weighted = [s for s in symbols if _usable(weights.get(s))]
        if not weighted:
            result.append(dataclasses.replace(sector, weighted_members=0, member_total=len(symbols)))
            continue
        cap = sum(weights[s] for s in weighted)
        impact = None if sector.change_pct is None else cap * sector.change_pct / 100.0
        result.append(
            dataclasses.replace(
                sector,
                free_float_cap=cap,
                impact_value=impact,
                weighted_members=len(weighted),
                member_total=len(symbols),
            )
        )
    return result


def order_sectors(sectors: Iterable[SectorMarketData], order: str) -> List[SectorMarketData]:
    """Tiles in the requested order (see the module docstring).

    Unknown orders fall back to ``performance``. Ties break by name, so equal
    values never swap places between refreshes.
    """
    sectors = list(sectors)
    if order == ORDER_BY_IMPACT:
        return sorted(
            sectors,
            key=lambda s: (
                s.impact_value is None,
                -abs(s.impact_value or 0.0),
                s.sector,
            ),
        )
    if order == ORDER_BY_SIZE:
        return sorted(
            sectors,
            key=lambda s: (s.free_float_cap is None, -(s.free_float_cap or 0.0), s.sector),
        )
    return rank_sectors(sectors)


def unweighted_tiles(sectors: Iterable[SectorMarketData]) -> List[str]:
    """Names of tiles with no usable weight - ranked last by size and impact."""
    return [s.sector for s in sectors if s.free_float_cap is None]


def partially_weighted_tiles(sectors: Iterable[SectorMarketData]) -> List[str]:
    """Names of tiles whose weight covers only some of their members."""
    return [
        s.sector
        for s in sectors
        if s.free_float_cap is not None and s.weighted_members < s.member_total
    ]


# --------------------------------------------------------------------------
# Formatting for tiles and tooltips
# --------------------------------------------------------------------------
def format_rupees(value: Optional[float], signed: bool = False) -> str:
    """Rupees as crore, or lakh crore once that is shorter: ``₹4,120 cr``, ``₹18.2 lakh cr``."""
    if value is None:
        return "-"
    sign = ("+" if value > 0 else "-" if value < 0 else "") if signed else ("-" if value < 0 else "")
    magnitude = abs(value)
    if magnitude >= LAKH_CRORE:
        return f"{sign}₹{magnitude / LAKH_CRORE:,.1f} lakh cr"
    return f"{sign}₹{magnitude / CRORE:,.0f} cr"


def sector_weight_line(sector: SectorMarketData, index_name: str) -> str:
    """Third tile line on the Nifty 50 board: share of the index and impact."""
    if sector.index_share_pct is None:
        return "no weight"
    parts = [f"{sector.index_share_pct:.1f}% of {index_name}"]
    if sector.index_impact_points is not None:
        parts.append(f"{sector.index_impact_points:+.0f} pts")
    elif sector.index_impact_pct is not None:
        parts.append(f"impact {sector.index_impact_pct:+.2f}%")
    return " · ".join(parts)


def index_close_for_points(index: Optional[StockMarketData]) -> Optional[float]:
    """The index's previous close to turn impact into points, or None to stay in %.

    ``index`` is ``MarketSnapshot.index``. Its previous close follows the same
    rule as the stocks' (OHLC in session, daily candles outside it), so when it
    is missing the honest answer is "no points", never a guess.
    """
    if index is None or index.previous_close is None or index.previous_close <= 0:
        return None
    return index.previous_close


def index_points_note(index: Optional[StockMarketData], index_name: str, provider: str = "") -> str:
    """Caption fragment saying what unit the impact is in, and why when it is not points."""
    if index_close_for_points(index) is not None:
        return "in index points (from the index's previous close, on the same feed). "
    if not provider:
        return "in % of the index until the feed has connected and priced the index itself. "
    if index is None:
        reason = f"{provider} does not serve the {index_name} index itself"
    else:
        reason = f"{provider} has not supplied the {index_name} index's previous close"
    return f"in % of the index - {reason}, so points cannot be shown. "


def index_level_text(index: Optional[StockMarketData]) -> Optional[str]:
    """``24,812.35 (+0.42%)`` for the board header, or None while the index has no price."""
    if index is None or index.ltp is None or index.ltp <= 0:
        return None
    change = index.change_pct
    return f"{index.ltp:,.2f}" + (f" ({change:+.2f}%)" if change is not None else "")


def index_weight_line(sector: SectorMarketData) -> str:
    """Third tile line on the index board: free-float cap and rupee impact."""
    if sector.free_float_cap is None:
        return "no weight"
    parts = [format_rupees(sector.free_float_cap)]
    if sector.impact_value is not None:
        parts.append(format_rupees(sector.impact_value, signed=True))
    return " · ".join(parts)


def sector_impact_tooltip(sector: SectorMarketData, index_name: str) -> str:
    """Hover detail for the weight line on the Nifty 50 board."""
    if sector.index_share_pct is None:
        return f"No stored weight for any {sector.sector} member - ranked last by size and impact."
    text = (
        f"{sector.index_share_pct:.1f}% of {index_name} by free-float market cap"
        f" ({sector.weighted_members}/{sector.member_total} members weighted)."
    )
    if sector.cap_weighted_change_pct is not None and sector.index_impact_pct is not None:
        text += (
            f" Market-cap weighted move {sector.cap_weighted_change_pct:+.2f}%,"
            f" so it moved {index_name} by {sector.index_impact_pct:+.3f}%"
        )
        if sector.index_impact_points is not None:
            text += f" ({sector.index_impact_points:+.1f} points)"
        text += "."
    return text


def index_weight_tooltip(sector: SectorMarketData) -> str:
    """Hover detail for the weight line on the index board."""
    if sector.free_float_cap is None:
        if sector.member_total == 0:
            return "No constituent list stored - ranked last by size and impact."
        return "No stored weight for its constituents - ranked last by size and impact."
    text = (
        f"Free-float market cap {format_rupees(sector.free_float_cap)}"
        f" ({sector.weighted_members}/{sector.member_total} constituents weighted)."
    )
    if sector.impact_value is not None:
        text += f" Today's move is worth {format_rupees(sector.impact_value, signed=True)}."
    return text
