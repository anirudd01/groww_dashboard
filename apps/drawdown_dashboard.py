"""Drop from high: how far each stock trades below its high over a window, as a treemap.

Each tile is a stock, sized by free-float market cap and coloured by its drop from the
highest intraday high in the window (52 weeks, year to date, 2 or 5 years, or since a date).
Tiles can be boxed by sector; the outer box is the whole universe. A range filter keeps only
the stocks within a band of drops (near the high, down 20% or more, ...). See
market/drawdown.py and docs/DROP_FROM_HIGH.md.

Data comes only from the stored daily bars in data/market.db, written by
scripts/kite.py history. Every figure is computed in SQLite; the page makes no API call.

Visualisation only - it places no orders and generates no signals.

This is the "Drop from High" page of pulse_dashboard.py; to run it on its own:

    streamlit run apps/drawdown_dashboard.py --server.port 8511
"""

import os as _os
import sys as _sys

# Repo root on the path, so `market` and `ui` import when this file is run directly.
_sys.path.insert(0, _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))))


from datetime import date, timedelta

import pandas as pd
import streamlit as st

from market import drawdown as dd
from market.fno_movers import CONFIRM_SCRIPT, UPDATE_SCRIPT, closes_stamp, load_universe
from market.index_constituents import load_sectors
from market.market_hours import now_ist
from market.universe import universes
from market.weights import load_weights
from ui.drawdown_treemap import build_drawdown_treemap, sectors_frame, stocks_frame

UNIVERSE_NIFTY50 = "Nifty 50"
UNIVERSE_NIFTY100 = "Nifty 100"
UNIVERSE_NEXT50 = "Nifty Next 50"
UNIVERSE_FNO = "All F&O"
UNIVERSE_OPTIONS = (UNIVERSE_NIFTY50, UNIVERSE_NIFTY100, UNIVERSE_NEXT50, UNIVERSE_FNO)

SIZE_CAP = "Market cap"
SIZE_EQUAL = "Equal"

#: The history is called stale once its last day is this many calendar days old.
STALE_AFTER_DAYS = 4


def universe_symbols(label: str) -> list:
    """The stocks of a universe; the Nifty lists come from NSE's stored constituents."""
    if label == UNIVERSE_FNO:
        return sorted(load_universe().tokens)
    stored = universes()
    keys = {UNIVERSE_NIFTY50: ["NIFTY50"], UNIVERSE_NEXT50: ["NIFTYNEXT50"],
            UNIVERSE_NIFTY100: ["NIFTY50", "NIFTYNEXT50"]}[label]
    return sorted({s for key in keys if key in stored for s in stored[key].symbols})


@st.cache_data(ttl="10m", show_spinner=False)
def compute(stamp: float, symbols: tuple, start: str, as_of: str, reset: bool):
    """``(drawdowns, suspected actions)``. ``stamp`` busts the cache when the database changes."""
    actions = dd.suspected_actions(symbols, start, as_of)
    rows = dd.drawdowns(symbols, start, as_of, resets=dd.resets_for(actions) if reset else None)
    return rows, actions


@st.cache_data(ttl="1h", show_spinner=False)
def reference(stamp: float):
    """Sector labels and free-float market caps (both generated by the ``--master`` runs)."""
    return load_sectors(), load_weights().weights


def main() -> None:
    st.title("Drop from high")
    st.caption(
        "How far each stock trades below its highest price over a window. A tile is a stock, sized by "
        "free-float market cap; green is at the high, darker red is further below it. The high is the "
        "highest intraday high in the window, the same definition NSE uses for the 52-week high."
    )

    first, last = dd.stored_range()
    if not last:
        st.error(f"No daily history stored. Run 'python {UPDATE_SCRIPT} --full --history-days 1830'.",
                 icon=":material/error:")
        st.stop()
    first_day, last_day = date.fromisoformat(first), date.fromisoformat(last)

    with st.sidebar:
        label = st.segmented_control("Stocks", UNIVERSE_OPTIONS, default=UNIVERSE_NIFTY50, required=True,
                                     key="dd_universe")
        window = st.segmented_control("High over", dd.WINDOWS, default=dd.WINDOW_52W, required=True,
                                      key="dd_window")
        as_of = st.date_input("As of", value=last_day, min_value=first_day, max_value=last_day, key="dd_as_of",
                              help="The close compared with the high. Pick an earlier day to see the board "
                                   "as it stood then.")
        custom = None
        if window == dd.WINDOW_CUSTOM:
            custom = st.date_input("High since", value=max(first_day, as_of - timedelta(days=90)),
                                   min_value=first_day, max_value=as_of, key="dd_since",
                                   help="For example the day the Nifty last peaked.").isoformat()
        band = st.slider("Show stocks whose drop is between", -100, 0, (-100, 0), step=1, format="%d%%",
                         key="dd_band", help="-100 to -20 keeps the stocks down 20% or more; -5 to 0 keeps "
                                             "the ones within 5% of their high.")
        grouped = st.toggle("Group by sector", value=True, key="dd_grouped")
        size = st.segmented_control("Tile size", [SIZE_CAP, SIZE_EQUAL], default=SIZE_CAP, required=True,
                                    key="dd_size")
        reset = st.toggle("Measure from after a suspected split/demerger", value=True, key="dd_reset",
                          help="Kite's history is adjusted for splits and bonuses but not demergers, so a "
                               "demerged stock's old high would show as a fake drop. With this on, a stock "
                               "with a split-like fall in the window is measured from that day.")

    as_of_text = as_of.isoformat()
    start = dd.window_start(window, as_of_text, custom)
    symbols = universe_symbols(label)
    if not symbols:
        st.error(f"No {label} list stored. Run 'python scripts/kite.py --master'.", icon=":material/error:")
        st.stop()
    stamp = closes_stamp()
    every, actions = compute(stamp, tuple(symbols), start, as_of_text, reset)
    sectors, caps = reference(stamp)
    weights = caps if size == SIZE_CAP else None
    shown = [r for r in every if band[0] <= r.drop_pct <= band[1]]

    whole = dd.summarise(label, every, caps)
    with st.container(horizontal=True):
        st.metric("Stocks", f"{len(shown)}/{len(every)}", border=True,
                  help="Shown after the drop filter / in the universe with history in the window.")
        st.metric("Median from high", f"{whole.median_drop_pct:+.1f}%", border=True,
                  help=f"Median over all {whole.count} {label} stocks, whatever the filter.")
        st.metric("Cap-weighted from high", f"{whole.weighted_drop_pct:+.1f}%", border=True,
                  help="Drops averaged by free-float market cap: roughly the index-level view, but a "
                       "stock's own high, not the index's.")
        st.metric(f"Within {dd.NEAR_HIGH_PCT:.0f}% of high", whole.near_high, border=True)
        st.metric(f"Down {dd.DEEP_DROP_PCT:.0f}%+", whole.deep_drop, border=True)

    st.caption(
        f"**{window}**: highs from {pd.Timestamp(start):%d %b %Y} to {pd.Timestamp(as_of_text):%d %b %Y}, "
        f"against the close of {pd.Timestamp(as_of_text):%a %d %b %Y}. Data source: the stored daily bars in "
        f"data/market.db (Kite, adjusted for splits and bonuses), no live prices and no API call. "
        f"Tiles marked * are measured over less than the window (see the table's Note)."
    )
    if start < first:
        st.warning(f"The stored history starts on {first}, after the window does: stocks are measured "
                   f"from {first}.", icon=":material/history:")
    if (now_ist().date() - last_day).days > STALE_AFTER_DAYS:
        st.warning(f"The history ends on {last}. Run 'python {UPDATE_SCRIPT}' to catch up.",
                   icon=":material/history:")
    missing = sorted(set(symbols) - {r.symbol for r in every})
    if missing:
        st.caption(f"No bars in the window: {', '.join(missing)}.")
    if actions:
        listed = "; ".join(f"{a.symbol} {a.date} ({a.change_pct:+.1f}%)" for a in actions)
        how = "measured from that day" if reset else "measured over the whole window (the toggle is off)"
        st.info(f"Suspected split or demerger in the window, {how}: {listed}. If a fall was real, record it "
                f"with 'python {CONFIRM_SCRIPT} add SYMBOL DATE \"why\"' and it is measured normally.",
                icon=":material/call_split:")

    with st.container(border=True):
        if not shown:
            st.info("No stock's drop is inside the filter band.", icon=":material/filter_alt_off:")
        else:
            root = label if len(shown) == len(every) else f"{label}: {len(shown)} of {len(every)}"
            st.plotly_chart(build_drawdown_treemap(shown, root, sectors if grouped else None, weights),
                            width="stretch", key="dd_treemap", config={"displayModeBar": False})

    stock_tab, sector_tab = st.tabs([f"Stocks ({len(shown)})", "Sectors"])
    table = stocks_frame(shown, sectors)
    with stock_tab:
        st.dataframe(table, hide_index=True, column_config={
            "From high %": st.column_config.NumberColumn(format="%+.2f%%"),
            "Above low %": st.column_config.NumberColumn(format="%+.1f%%"),
            "Close": st.column_config.NumberColumn(format="%.2f"),
            "High": st.column_config.NumberColumn(format="%.2f"),
            "Low": st.column_config.NumberColumn(format="%.2f"),
        })
    with sector_tab:
        st.caption("Over the stocks the filter shows. Weighted = averaged by free-float market cap.")
        st.dataframe(sectors_frame(dd.by_sector(shown, sectors, caps)), hide_index=True, column_config={
            "Weighted from high %": st.column_config.NumberColumn(format="%+.2f%%"),
            "Median from high %": st.column_config.NumberColumn(format="%+.2f%%"),
        })

    with st.sidebar:
        st.divider()
        st.download_button("Download the table (CSV)", table.to_csv(index=False),
                           f"drop_from_high_{label.replace(' ', '_').replace('&', '')}_{as_of_text}.csv",
                           mime="text/csv", icon=":material/download:")


if __name__ == "__main__":
    st.set_page_config(page_title="Drop from high", page_icon=":material/trending_down:", layout="wide")
    main()
